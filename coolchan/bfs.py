def block_mesh_dict(p: BFSParams) -> str:
    S, h = p.S_mm, p.h_mm
    Ld, Lin = p.Ld_S * S, p.Lin_S * S
    Z = p.W_half_mm if p.is3d else S / p.n_S
    c = p.counts()
    gz = p.z_grading if p.is3d else 1.0
    V = [(0, 0), (Ld, 0), (Ld, S), (0, S), (Ld, S + h), (0, S + h), (-Lin, S), (-Lin, S + h)]
    verts = [(x, y, 0.0) for x, y in V] + [(x, y, Z) for x, y in V]
    vtxt = "\n".join(f"    ({x:.6g} {y:.6g} {z:.6g})  // {i}" for i, (x, y, z) in enumerate(verts))
    blocks = [
        f"    hex (0 1 2 3 8 9 10 11)   ({c['nxd']} {c['nyS']} {c['nz']}) simpleGrading (1 1 {gz})",
        f"    hex (3 2 4 5 11 10 12 13) ({c['nxd']} {c['nyh']} {c['nz']}) simpleGrading (1 1 {gz})",
    ]
    inlet = "(6 14 15 7)" if Lin > 0 else "(3 11 13 5)"
    top = "(5 4 12 13)" + (" (7 5 13 15)" if Lin > 0 else "")
    z0 = ["(0 3 2 1)", "(3 5 4 2)"] + (["(6 7 5 3)"] if Lin > 0 else [])
    z1 = ["(8 9 10 11)", "(11 10 12 13)"] + (["(14 11 13 15)"] if Lin > 0 else [])
    if Lin > 0:
        blocks.append(f"    hex (6 3 5 7 14 11 13 15) ({c['nxi']} {c['nyh']} {c['nz']}) simpleGrading (1 1 {gz})")
    extra = f"    inletBottomWall {{ type wall; faces ((6 3 11 14)); }}\n" if Lin > 0 else ""
    if p.is3d:
        zp = (f"    midPlane {{ type symmetryPlane; faces ({' '.join(z0)}); }}\n"
              f"    sideWall {{ type wall; faces ({' '.join(z1)}); }}\n")
    else:
        zp = f"    frontAndBack {{ type empty; faces ({' '.join(z0 + z1)}); }}\n"
    return f"""FoamFile {{ version 2.0; format ascii; class dictionary; object blockMeshDict; }}
// Backward-facing step, generated by coolchan/bfs.py
// S = {S} mm, h = {h} mm, ER = {p.ER:.3f}, Re(U_mean 2h/nu) = {p.Re:g}, {'3D half-span' if p.is3d else '2D'}

convertToMeters 0.001;

vertices
(
{vtxt}
);

blocks
(
{chr(10).join(blocks)}
);

boundary
(
    inlet      {{ type patch; faces ({inlet}); }}
    outlet     {{ type patch; faces ((1 2 10 9) (2 4 12 10)); }}
    bottomWall {{ type wall;  faces ((0 1 9 8)); }}
    stepWall   {{ type wall;  faces ((0 8 11 3)); }}
    topWall    {{ type wall;  faces ({top}); }}
{extra}{zp});
"""


def build_bfs(case_dir: Path, p: BFSParams) -> Path:
    case_dir = Path(case_dir)
    if case_dir.exists():
        shutil.rmtree(case_dir)
    toks = dict(nu=NU_AIR, nIter=p.nIter, writeInterval=max(1, p.nIter // 10),
                nProcs=p.nProcs)
    _copy_render(TEMPLATES / "bfs", case_dir, toks)
    (case_dir / "system" / "blockMeshDict").write_text(block_mesh_dict(p))
    (case_dir / "params.json").write_text(__import__("json").dumps(asdict(p)))
    return case_dir


