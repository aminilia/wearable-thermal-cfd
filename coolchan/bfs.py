def _crossings(x, u):
    """x positions where u changes sign, with direction (+1: - to +, -1: + to -)."""
    s = np.sign(u)
    out = []
    for i in np.where(s[:-1] * s[1:] < 0)[0]:
        xc = x[i] - u[i] * (x[i + 1] - x[i]) / (u[i + 1] - u[i])
        out.append((xc, 1 if u[i] < 0 else -1))
    return out


def reattachment(case_dir, p: BFSParams, time=None) -> dict:
    """Separation/reattachment lengths in step heights, on the mid-span plane.

    x1: lower-wall reattachment; x4, x5: upper-wall separation and reattachment
    (Armaly et al. notation). Uses the sign of u in the wall-adjacent cells.
    """
    c = Case(case_dir)
    m = c.mesh("")
    U = c.field("U", "", time).internal[:, 0]
    S = p.S_mm * 1e-3
    res = {}
    for patch, key in (("bottomWall", "lower"), ("topWall", "upper")):
        cells = m.patch_cells(patch)
        xc = m.C[cells, 0]
        if p.is3d:
            zc = m.C[cells, 2]
            sel = np.isclose(zc, zc.min())            # row nearest the symmetry plane
            cells, xc = cells[sel], xc[sel]
        keep = xc > 0
        o = np.argsort(xc[keep])
        res[key] = _crossings(xc[keep][o] / S, U[cells[keep][o]])
    lower = res["lower"]
    x1 = max((x for x, d in lower if d == 1), default=np.nan)
    upper = res["upper"]
    x4 = next((x for x, d in upper if d == -1), np.nan)
    x5 = next((x for x, d in upper if d == 1 and x > x4), np.nan)
    out = dict(x1=float(x1), x4=float(x4), x5=float(x5))
    log = Path(case_dir) / "log.simpleFoam"
    if log.exists():
        r = final_residuals(log)
        out["max_residual"] = max(r.values()) if r else np.nan
    return out


def reattachment_span(case_dir, p: BFSParams, time=None):
    """Lower-wall reattachment x1/S for every spanwise row of cells (3D cases)."""
    c = Case(case_dir)
    m = c.mesh("")
    U = c.field("U", "", time).internal[:, 0]
    S = p.S_mm * 1e-3
    cells = m.patch_cells("bottomWall")
    x, z = m.C[cells, 0], np.round(m.C[cells, 2], 9)
    zs = np.unique(z)
    x1 = []
    for zz in zs:
        sel = (z == zz) & (x > 0)
        o = np.argsort(x[sel])
        cr = _crossings(x[sel][o] / S, U[cells[sel]][o])
        x1.append(max((a for a, d in cr if d == 1), default=np.nan))
    return zs / S, np.array(x1)


def reattachment_iter_change(case_dir, p: BFSParams) -> float:
    t = Case(case_dir).times()
    if len(t) < 3:
        return float("nan")
    a = reattachment(case_dir, p, t[-1])["x1"]
    b = reattachment(case_dir, p, t[-2])["x1"]
    return abs(a - b)
