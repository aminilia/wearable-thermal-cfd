"""Backward-facing-step (BFS) validation cases: geometry, inlet profiles, analysis.

Geometry (x streamwise, y wall-normal, z spanwise; step at x = 0)::

        y = S+h  +-------------------------------------------------+ topWall
                 |  inlet channel |                                 |
   inlet --->    |   (length Lin) |                                 | outlet
        y = S    +----------------+                                 |
                  inletBottomWall |stepWall                         |
        y = 0                     +---------------------------------+ bottomWall
                 x = -Lin        x = 0                             x = Ld

2D cases are one cell thick (``frontAndBack`` empty). 3D cases model half the
span: ``midPlane`` (z = 0) is a symmetry plane and ``sideWall`` (z = W/2) is a
no-slip wall, which is what introduces the sidewall three-dimensionality that
Armaly et al. (1983) observed above Re ~ 400.
"""
from __future__ import annotations

import math
import shutil
from dataclasses import dataclass, asdict
from pathlib import Path

import numpy as np

from .case import AIR, TEMPLATES, _copy_render
from .foamio import Case, PolyMesh, final_residuals

NU_AIR = AIR["mu_air"] / AIR["rho_air"]


@dataclass
class BFSParams:
    Re: float                  # U_mean * 2h / nu   (Armaly et al. 1983 definition)
    S_mm: float = 4.9          # step height
    h_mm: float = 5.2          # inlet-channel height  (ER = (S+h)/h = 1.942)
    Lin_S: float = 5.0         # inlet-channel length / S (0 -> profile imposed at the step)
    Ld_S: float = 40.0         # downstream length / S
    n_S: int = 20              # cells per step height (y)
    aspect: float = 2.0        # dx / dy
    W_half_mm: float | None = None   # half-span for 3D (None -> 2D)
    nz: int = 30               # spanwise cells (3D)
    z_grading: float = 0.1     # last/first spanwise cell size (fine at the sidewall)
    nIter: int = 4000
    nProcs: int = 1

    @property
    def U_mean(self) -> float:
        return self.Re * NU_AIR / (2 * self.h_mm * 1e-3)

    @property
    def ER(self) -> float:
        return (self.S_mm + self.h_mm) / self.h_mm

    @property
    def is3d(self) -> bool:
        return self.W_half_mm is not None

    def counts(self):
        dy = self.S_mm / self.n_S
        dx = self.aspect * dy
        n = lambda L, d: max(1, int(round(L / d)))
        return dict(nyS=self.n_S, nyh=n(self.h_mm, dy),
                    nxd=n(self.Ld_S * self.S_mm, dx), nxi=n(self.Lin_S * self.S_mm, dx),
                    nz=self.nz if self.is3d else 1)

    def n_cells(self) -> int:
        c = self.counts()
        cells = c["nxd"] * (c["nyS"] + c["nyh"])
        if self.Lin_S > 0:
            cells += c["nxi"] * c["nyh"]
        return cells * c["nz"]


