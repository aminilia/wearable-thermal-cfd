def duct_profile(y, z, a, b, n_terms=41):
    """Fully developed laminar u(y, z) in a rectangular duct |y|<=a, |z|<=b (unscaled).

    White, Viscous Fluid Flow, eq. 3-48 (series in odd i).
    """
    u = np.zeros_like(y, dtype=float)
    for i in range(1, 2 * n_terms, 2):
        k = i * math.pi / (2 * a)
        # cosh ratio written with exponentials to avoid overflow for wide ducts
        ratio = np.exp(k * (np.abs(z) - b)) * (1 + np.exp(-2 * k * np.abs(z))) / (1 + math.exp(-2 * k * b))
        u += (-1) ** ((i - 1) // 2) * (1 - ratio) * np.cos(k * y) / i**3
    return u


def write_inlet_velocity(case_dir: Path, p: BFSParams):
    """Write 0/air/U with the exact fully developed profile on the inlet faces."""
    case_dir = Path(case_dir)
    m = PolyMesh(case_dir / "constant" / "polyMesh")
    Cf = m.patch_centres("inlet") * 1e3           # mm
    A = np.linalg.norm(m.patch_areas("inlet"), axis=1)
    yc = Cf[:, 1] - (p.S_mm + p.h_mm / 2)         # centred in the inlet channel
    if p.is3d:
        u = duct_profile(yc, Cf[:, 2], p.h_mm / 2, p.W_half_mm)
    else:
        eta = (Cf[:, 1] - p.S_mm) / p.h_mm
        u = eta * (1 - eta)
    if p.is3d:
        # Armaly et al. define Re with V = 2/3 of the measured centre-line maximum, so
        # match that (the duct bulk velocity is ~1.8 % lower for aspect ratio 36)
        u *= 1.5 * p.U_mean / u.max()
    else:
        u *= p.U_mean / ((u * A).sum() / A.sum())   # exact bulk velocity -> exact Re
    vals = "\n".join(f"({v:.8g} 0 0)" for v in u)
    Ui = p.U_mean * p.h_mm / (p.S_mm + p.h_mm)
    txt = f"""FoamFile {{ version 2.0; format ascii; class volVectorField; location "0"; object U; }}
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform ({Ui:.6g} 0 0);

boundaryField
{{
    inlet
    {{
        type            fixedValue;     // fully developed profile, U_mean = {p.U_mean:.6g} m/s
        value           nonuniform List<vector> {len(u)}
(
{vals}
);
    }}
    outlet          {{ type inletOutlet; inletValue uniform (0 0 0); value $internalField; }}
    ".*Wall"        {{ type noSlip; }}
    midPlane        {{ type symmetryPlane; }}
    frontAndBack    {{ type empty; }}
}}
"""
    d = case_dir / "0"
    if d.exists():
        shutil.rmtree(d)
    shutil.copytree(case_dir / "0.orig", d)
    (d / "U").write_text(txt)


